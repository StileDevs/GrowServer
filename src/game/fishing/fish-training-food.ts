/** Returns 0 when this species cannot eat the selected fish/crab. */
export function getTrainingFoodXp(speciesId: number, foodId: number, pounds: number): number {
  const multiplier = TRAINING_FOOD_MULTIPLIERS[speciesId]?.[foodId];
  if (multiplier === undefined || !Number.isSafeInteger(pounds) || pounds <= 0) return 0;
  return Math.max(1, Math.round(pounds * multiplier));
}
